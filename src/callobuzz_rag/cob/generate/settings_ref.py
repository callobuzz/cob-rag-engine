"""The settings reference: one Markdown page per `.env.example` group.

Every `RAG_*` setting appears with its default and what it does. The description is the
`Field(description=...)` when there is one, else the comment above the variable in
`.env.example` (the text people already read). Variables only the Compose files read
(`COMPOSE_PROFILES`, `SCRAPER_CORS_ORIGINS`, the host ports) are listed too.
"""

import re
from dataclasses import dataclass
from pathlib import Path

from pydantic import SecretStr
from pydantic_core import PydanticUndefined

from callobuzz_rag.cob.sources.common import slugify
from callobuzz_rag.core.config import Settings

OUT_DIR = Path("docs") / "cob" / "generated" / "settings"

_ACTIVE = re.compile(r"^([A-Z][A-Z0-9_]*)=(.*)$")
_COMMENTED = re.compile(r"^# ([A-Z][A-Z0-9_]*)=(.*)$")
_SUBGROUP = re.compile(r"^# --- (.+?) ---\s*$")
_SECTION = re.compile(r"^# \d+\. (.+)$")
_RULE = re.compile(r"^# =+\s*$")
_SECRETISH = re.compile(r"(PASSWORD|SECRET|_KEY|SALT|TOKEN)", re.IGNORECASE)


@dataclass
class EnvVar:
    name: str
    group: str
    comment: str
    example: str
    commented_out: bool


def _group_name(section_title: str) -> str:
    """'Embeddings (how documents ...)' becomes 'Embeddings', 'REQUIRED: fill these in'
    becomes 'Required'."""
    title = section_title.split(":", 1)[0]
    title = re.sub(r"\s*\(.*$", "", title).strip()
    return title.capitalize() if title.isupper() else title


def parse_env_example(text: str) -> list[EnvVar]:
    out: list[EnvVar] = []
    section = "Settings"
    subgroup: str | None = None
    comment: list[str] = []
    previous_was_var = False
    lines = text.splitlines()
    for i, line in enumerate(lines):
        previous_line = lines[i - 1] if i else ""
        section_match = _SECTION.match(line)
        if section_match and _RULE.match(previous_line):
            section = _group_name(section_match.group(1))
            subgroup = None
            comment = []
            previous_was_var = False
            continue
        sub = _SUBGROUP.match(line)
        if sub:
            subgroup = _group_name(sub.group(1))
            comment = []
            previous_was_var = False
            continue
        active = _ACTIVE.match(line)
        commented = None if active else _COMMENTED.match(line)
        match = active or commented
        if match:
            text_comment = " ".join(comment) if comment else ""
            if not comment and previous_was_var and out:
                text_comment = out[-1].comment
            out.append(
                EnvVar(
                    name=match.group(1),
                    group=subgroup or section,
                    comment=text_comment,
                    example=match.group(2).strip(),
                    commented_out=active is None,
                )
            )
            comment = []
            previous_was_var = True
            continue
        previous_was_var = False
        if line.startswith("# ") and not _RULE.match(line):
            comment.append(line[2:].strip())
        elif line.strip() == "" or _RULE.match(line):
            comment = []
    return out


def _show(value: object) -> str:
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if value is None or value == "" or value == [] or value == {}:
        return "empty"
    return f"`{value}`"


def _field_default(name: str) -> tuple[str, bool]:
    """(how the default reads, whether the setting is secret)."""
    field = Settings.model_fields[name]
    if isinstance(field.default, SecretStr):
        return "secret, no default", True
    if field.default is PydanticUndefined:
        factory = field.default_factory
        return _show(factory() if factory else None), False  # type: ignore[call-arg]
    return _show(field.default), False


def _body(var: EnvVar | None, name: str) -> str:
    env_name = name
    field_name = env_name.removeprefix("RAG_").lower()
    field = Settings.model_fields.get(field_name) if env_name.startswith("RAG_") else None
    parts: list[str] = []
    description = (field.description if field and field.description else "") or (
        var.comment if var else ""
    )
    parts.append(description or "No description yet.")
    if field is not None:
        default, secret = _field_default(field_name)
        line = f"Default: {default}."
        if var and not secret and var.example and not var.commented_out:
            shown = _show(var.example)
            if shown != _show(field.default if field.default is not PydanticUndefined else ""):
                line += f" `.env.example` sets {shown}."
        parts.append(line)
    elif var is not None:
        if _SECRETISH.search(env_name) and not var.example:
            parts.append("Default: empty (generated by `make setup`).")
        else:
            parts.append(f"Default: {_show(var.example)}. Read by Docker Compose, not the engine.")
    return "\n\n".join(parts)


def _page(group: str, entries: list[tuple[str, str]]) -> str:
    title = f"{group} settings"
    out = [
        "---",
        f"title: {title}",
        "audience: admin",
        "topic: settings",
        f"summary: Environment variables in the {group} group of the engine's .env file.",
        "---",
        f"Environment variables in the **{group}** group. Set them in the `.env` file at the "
        "repository root (the template is `.env.example`) and restart the app, worker and "
        "mailer. Names start with `RAG_` unless noted.",
        "",
    ]
    for name, body in entries:
        out += [f"## `{name}`", "", body, ""]
    return "\n".join(out).rstrip() + "\n"


def render_settings_pages(root: Path) -> dict[str, str]:
    """Relative path (posix) to file content."""
    example = (root / ".env.example").read_text(encoding="utf-8")
    variables = parse_env_example(example)
    by_group: dict[str, list[tuple[str, str]]] = {}
    documented: set[str] = set()
    for var in variables:
        if var.name in documented:
            continue
        documented.add(var.name)
        by_group.setdefault(var.group, []).append((var.name, _body(var, var.name)))
    missing = sorted(
        f"RAG_{name.upper()}"
        for name in Settings.model_fields
        if f"RAG_{name.upper()}" not in documented
    )
    if missing:
        by_group["Other settings"] = [(name, _body(None, name)) for name in missing]
    files: dict[str, str] = {}
    used: set[str] = set()
    for group, entries in by_group.items():
        stem = slugify(group)
        while stem in used:
            stem += "-2"
        used.add(stem)
        files[(OUT_DIR / f"{stem}.md").as_posix()] = _page(group, entries)
    return files
