"""The consolidated smoke summary: one row per `smoke-*` run, from the files on disk (free).

Checks per model, on its three smoke items (`items.SMOKE_ITEM_IDS`):
- **en**: gold fact stated, no forbidden fact;
- **hi**: a Markdown table, every gold fact, no forbidden fact;
- **hl**: the unanswerable question gets the no-answer reply;
- **claim check**: the RELEASED answer (after the engine's fact gate) keeps every gold fact
  and states no forbidden fact, on all three items; gate false removals are counted beside it;
- **thinking off**: 0 reasoning tokens, no reasoning stream, no think markers in the text.

Verdict PASS needs a clean capture gate (`verify.verify_run`: every field present, no rail
failure), thinking off honoured and every check above; DROP = the model thinks despite off.
"""

import re
import statistics
from dataclasses import dataclass
from pathlib import Path

from benchmarks.answer_bench.items import SMOKE_ITEM_IDS, Item, select_items
from benchmarks.answer_bench.records import (
    AnswerRecord,
    RunManifest,
    ScoreRecord,
    read_jsonl,
)
from benchmarks.answer_bench.verify import verify_run

_THINK = re.compile(r"</?think>|<\|?thinking\|?>", re.IGNORECASE)
_LABELS = {"en-a-01": "en", "hi-t-01": "hi", "hl-u-01": "hl"}


@dataclass
class Row:
    model: str
    verdict: str
    hosts: list[str]
    ttft: list[int | None]
    total: list[int]
    tokens: tuple[int, int, int]
    costs: list[float | None]
    thinking_off: bool
    checks: dict[str, bool]
    claim_ok: int
    false_removals: int
    truncated: list[str]
    problems: list[str]

    @property
    def cost(self) -> float:
        return sum(c or 0.0 for c in self.costs)


def _check(item_id: str, s: ScoreRecord) -> bool:
    if item_id.startswith("en-"):
        return s.gold_recall == 1.0 and not s.forbidden_hits
    if item_id.startswith("hi-"):
        return s.table_present and s.gold_recall == 1.0 and not s.forbidden_hits
    return s.refusal_correct


def build_row(run_dir: Path, items: list[Item]) -> Row:
    manifest = RunManifest.model_validate_json((run_dir / "run.json").read_text("utf-8"))
    answers = {r.item_id: r for r in read_jsonl(run_dir / "answers.jsonl", AnswerRecord)}
    scores = {s.item_id: s for s in read_jsonl(run_dir / "scores.jsonl", ScoreRecord)}
    chosen = select_items(items, ids=list(SMOKE_ITEM_IDS))
    report = verify_run(run_dir, chosen, manifest.models, manifest.variants, require_host=True)
    recs: list[AnswerRecord] = [answers[i] for i in SMOKE_ITEM_IDS if i in answers]
    hosts: list[str] = []
    for r in recs:
        for h in (r.host or "unknown").split(","):
            if h.strip() and h.strip() not in hosts:
                hosts.append(h.strip())
    thinking_off = all(
        (r.tokens_reasoning or 0) == 0 and not r.reasoning_seen and not _THINK.search(r.answer_raw)
        for r in recs
    )
    checks = {
        _LABELS[i]: (i in scores and _check(i, scores[i])) for i in SMOKE_ITEM_IDS if i in _LABELS
    }
    claim_ok = sum(1 for i in SMOKE_ITEM_IDS if i in scores and scores[i].claim_check_pass)
    false_removals = sum(s.gate_false_removals for s in scores.values())
    ok = (
        report.ok
        and len(recs) == len(SMOKE_ITEM_IDS)
        and all(checks.values())
        and claim_ok == len(SMOKE_ITEM_IDS)
    )
    verdict = "DROP" if not thinking_off else ("PASS" if ok else "FAIL")
    return Row(
        model=manifest.models[0] if manifest.models else run_dir.name,
        verdict=verdict,
        hosts=hosts,
        ttft=[answers[i].ttft_ms if i in answers else None for i in SMOKE_ITEM_IDS],
        total=[answers[i].total_ms if i in answers else 0 for i in SMOKE_ITEM_IDS],
        tokens=(
            sum(r.tokens_in or 0 for r in recs),
            sum(r.tokens_out or 0 for r in recs),
            sum(r.tokens_reasoning or 0 for r in recs),
        ),
        costs=[answers[i].cost_usd if i in answers else None for i in SMOKE_ITEM_IDS],
        thinking_off=thinking_off,
        checks=checks,
        claim_ok=claim_ok,
        false_removals=false_removals,
        truncated=[r.item_id for r in recs if r.finish_reason == "length"],
        problems=report.problems,
    )


def _ms(values: list[int | None]) -> str:
    return " / ".join("-" if v is None else str(v) for v in values)


def _pf(ok: bool) -> str:
    return "pass" if ok else "FAIL"


def markdown(rows: list[Row], title: str) -> str:
    lines = [
        f"# {title}",
        "",
        "Thinking off, 3 items per model (en-a-01 answerable fact, hi-t-01 Hindi table, "
        "hl-u-01 Hinglish unanswerable), identical context, through the engine's grounded-answer "
        "path on OpenRouter. Generated by `python -m benchmarks.answers smoke-summary` from the "
        "saved runs (no model calls); `answer_released` re-derived from `answer_raw` by "
        "`python -m benchmarks.answers regate --all-smoke` with the current fact gate.",
        "",
        "Checks: **en** = gold fact found, no forbidden fact; **hi** = table present, table "
        "facts right, gold facts found; **hl** = unanswerable question gets the no-answer reply. "
        "**Claim check** = the released answer (after the fact gate) keeps every gold fact and "
        "states no forbidden fact, items passing of 3; **Gate false removals** = sentences the "
        "gate removed although every value in them is in the sources. **Thinking off** passes "
        "when reasoning tokens are 0, no reasoning stream was seen and no think markers leaked "
        "into the text. **Verdict**: PASS needs a clean capture gate (every field present, no "
        "rail failure), thinking off honoured, en / hi / hl passed and the claim check on all "
        "three; DROP = the model thinks despite off.",
        "",
        "| # | Model | Verdict | Host(s) | TTFT ms (en / hi / hl) | TTFT p50 | Total ms "
        "(en / hi / hl) | Tokens in / out / reasoning | Cost per item $ (en / hi / hl) | Cost $ "
        "| Thinking off | en | hi | hl | Claim check | Gate false removals | Rails / problems |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for n, r in enumerate(rows, 1):
        ttfts = [t for t in r.ttft if t is not None]
        p50 = str(round(statistics.median(ttfts))) if ttfts else "-"
        costs = " / ".join("-" if c is None else f"{c:.6f}" for c in r.costs)
        problems = "; ".join(r.problems) if r.problems else "none"
        lines.append(
            f"| {n} | `{r.model}` | **{r.verdict}** | {', '.join(r.hosts)} | {_ms(r.ttft)} "
            f"| {p50} | {_ms(list(r.total))} | {r.tokens[0]} / {r.tokens[1]} / {r.tokens[2]} "
            f"| {costs} | {r.cost:.5f} | {_pf(r.thinking_off)} "
            f"| {_pf(r.checks.get('en', False))} | {_pf(r.checks.get('hi', False))} "
            f"| {_pf(r.checks.get('hl', False))} | {r.claim_ok}/3 | {r.false_removals} "
            f"| {problems} |"
        )
    total = sum(r.cost for r in rows)
    dropped = [r.model for r in rows if r.verdict == "DROP"]
    failed = [r for r in rows if r.verdict == "FAIL"]
    lines += [
        "",
        f"Models: {len(rows)}. Total smoke spend (sum of the saved per-item costs): "
        f"**${total:.4f}**. Pass: {sum(r.verdict == 'PASS' for r in rows)}, "
        f"fail: {len(failed)}, dropped: {len(dropped)}.",
        "",
        f"Dropped for thinking despite off: {', '.join(dropped) if dropped else 'none'}.",
        "",
        "## Failures",
        "",
    ]
    if not failed:
        lines.append("None.")
    for r in failed:
        why = [k for k, ok in r.checks.items() if not ok]
        if r.claim_ok < 3:
            why.append(f"claim check {r.claim_ok}/3")
        if r.truncated:
            why.append(f"length stop on {', '.join(r.truncated)}")
        if r.problems:
            why.append("capture gate: " + "; ".join(r.problems))
        lines.append(f"- `{r.model}`: {', '.join(why) or 'see the row'}")
    lines.append("")
    return "\n".join(lines)


def smoke_runs(root: Path) -> list[Path]:
    return sorted(
        p
        for p in root.glob("smoke-*")
        if p.is_dir() and (p / "answers.jsonl").exists() and (p / "run.json").exists()
    )


def write(root: Path, out: Path, items: list[Item], title: str) -> list[Row]:
    rows = [build_row(run, items) for run in smoke_runs(root)]
    out.write_text(markdown(rows, title), "utf-8", newline="\n")
    return rows
