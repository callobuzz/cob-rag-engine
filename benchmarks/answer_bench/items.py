"""The frozen question set: every model answers each item from exactly the same passages.

`benchmarks/data/answers/items.jsonl` is committed and generated by `build_items.py` from the
real benchmark documents (benchmarks/documents/make_fixtures.py and benchmarks/documents/
furniture/). Changing it changes what is measured, so a run records the file's hash and refuses
to resume against a different one.
"""

import hashlib
import json
from pathlib import Path
from typing import Literal

from benchmarks.answer_bench import ITEMS_PATH
from pydantic import BaseModel, ConfigDict, Field, model_validator

Language = Literal["en", "hi", "hi-Latn"]
ItemType = Literal["answerable", "unanswerable", "table"]
Review = Literal["pending", "approved", "changes_requested", "n/a"]

# The smoke run's three items: one of each language and each type the run checks hardest
# (an English answer, a Hindi comparison table, a Hinglish question the passages cannot answer).
SMOKE_ITEM_IDS: tuple[str, ...] = ("en-a-01", "hi-t-01", "hl-u-01")


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Passage(_Strict):
    """One retrieved chunk as the answer model sees it (`[N] (source: ..., section: ...)`)."""

    id: str
    file_name: str
    section: str | None
    page: int | None
    text: str
    language: Language
    translated: bool = Field(description="A translation of `translation_of`, written for this set.")
    translation_of: str | None
    native_review: Review = Field(description="Native-speaker review of a translated passage.")


class Item(_Strict):
    id: str
    language: Language
    type: ItemType
    business: str = Field(description="The business the assistant speaks for.")
    question: str
    passages: list[Passage] = Field(min_length=3, max_length=6)
    gold_passages: list[int] = Field(
        description="1-based citation numbers of the passages holding the answer ([] when none)."
    )
    gold_facts: list[list[str]] = Field(
        description="Facts the answer must state; each is a list of accepted surface forms."
    )
    forbidden_facts: list[str] = Field(
        description="Plausible wrong values: stating one is a hallucination."
    )
    source: str = Field(description="Where the question comes from.")
    native_review: Review = Field(description="Native-speaker review of the question (SV).")
    notes: str

    @model_validator(mode="after")
    def _consistent(self) -> "Item":
        n = len(self.passages)
        if any(not 1 <= g <= n for g in self.gold_passages):
            raise ValueError(f"{self.id}: gold passage out of range")
        if self.type == "unanswerable" and self.gold_facts:
            raise ValueError(f"{self.id}: an unanswerable item has no gold facts")
        if self.type != "unanswerable" and not (self.gold_facts and self.gold_passages):
            raise ValueError(f"{self.id}: an answerable item needs gold facts and passages")
        if len({p.id for p in self.passages}) != n:
            raise ValueError(f"{self.id}: duplicate passage")
        return self


def item_hash(item: Item) -> str:
    """Hash of everything the model sees or the scorer reads for this item."""
    return hashlib.sha256(item.model_dump_json().encode("utf-8")).hexdigest()[:16]


def file_hash(path: Path = ITEMS_PATH) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_items(path: Path = ITEMS_PATH) -> list[Item]:
    items = [
        Item.model_validate(json.loads(line))
        for line in path.read_text("utf-8").splitlines()
        if line.strip()
    ]
    ids = [i.id for i in items]
    if len(set(ids)) != len(ids):
        raise ValueError("duplicate item ids in the item set")
    return items


def select_items(
    items: list[Item], *, ids: list[str] | None = None, limit: int | None = None
) -> list[Item]:
    """`ids` (in that order) when given, else the whole set; then the first `limit`."""
    if ids:
        by_id = {i.id: i for i in items}
        missing = [x for x in ids if x not in by_id]
        if missing:
            raise ValueError(f"unknown item ids: {', '.join(missing)}")
        items = [by_id[x] for x in ids]
    return items[:limit] if limit else items
