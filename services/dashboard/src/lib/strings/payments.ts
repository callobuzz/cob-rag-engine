/** Owner-facing label for a payment's purpose when the engine's own text is not at hand. */
export function purposeLabel(purpose: string): string {
	if (purpose === "plan") return paymentStrings.pay.forPlan;
	if (purpose === "add_on") return paymentStrings.pay.forAddOn;
	return paymentStrings.pay.forBalance;
}
