"""Phase 8: scope gap reports to a corpus.

`gap_report` recorded which corpus a run targeted only inside the `config_snapshot`
JSONB blob, so reports could not be filtered or tenant-scoped. This adds the real
column and backfills it from that blob.

Nullable on purpose: a detection run with no `corpus_id` legitimately spans every
corpus, and that "global run" state must stay representable.

Written by hand, NOT autogenerated — the ORM had drifted from the database
(golden_pair declared a FK to a non-existent `corpus` table), so autogenerate would
have emitted destructive DDL for that drift alongside this change.

Revision ID: phase8_002
Revises: phase8_001
Create Date: 2026-08-06
"""

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

revision: str = "phase8_002"
down_revision: str | None = "phase8_001"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade() -> None:
    op.add_column(
        "gap_report",
        sa.Column(
            "corpus_id",
            sa.dialects.postgresql.UUID(as_uuid=True),
            sa.ForeignKey("corpora.id", ondelete="CASCADE"),
            nullable=True,
        ),
    )
    op.create_index("ix_gap_report_corpus_id", "gap_report", ["corpus_id"])

    # Backfill from the JSONB snapshot the detector has always written.
    #
    # Two guards, both load-bearing:
    #   - the `~ uuid-regex` test, because config_snapshot is free-form JSONB and a
    #     malformed value would abort the whole migration on the ::uuid cast;
    #   - the EXISTS against corpora, because a corpus deleted since the run would
    #     violate the new FK. Those rows keep corpus_id NULL, which reads as
    #     "unknown scope" and is correct — the corpus is gone.
    op.execute(
        """
        UPDATE gap_report
           SET corpus_id = (config_snapshot->>'corpus_id')::uuid
         WHERE config_snapshot->>'corpus_id' IS NOT NULL
           AND config_snapshot->>'corpus_id'
               ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
           AND EXISTS (
                 SELECT 1 FROM corpora c
                  WHERE c.id = (config_snapshot->>'corpus_id')::uuid
               )
        """
    )


def downgrade() -> None:
    # Safe: the column holds only data denormalized from config_snapshot, which is
    # left untouched, so a downgrade loses no information.
    op.drop_index("ix_gap_report_corpus_id", table_name="gap_report")
    op.drop_column("gap_report", "corpus_id")
