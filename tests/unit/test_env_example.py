"""The env template must match the code: nothing a user can set is missing, nothing is invented.

`.env.example` is what people read and what `scripts/setup.py` writes from, so a setting that
exists in `core/config.py` but not here is invisible to them, and a variable here that nothing
reads is a trap.
"""

import re
from pathlib import Path

import pytest

from callobuzz_rag.core.config import Settings

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / (".en" + "v.example")

# Settings fields that are deliberately not offered to users. Empty on purpose: every setting
# is documented. Add a name here only with a reason next to it.
INTERNAL_FIELDS: set[str] = set()

# Variables that are neither a Settings field nor named in docker-compose.yml, its GPU overlay
# or the container entrypoint. Each needs a reason.
ALLOWLIST: dict[str, str] = {
    "COMPOSE_PROFILES": "read by `docker compose` itself, not by the engine or the compose file",
}

TEXT_SOURCES = [
    ROOT / "docker-compose.yml",
    ROOT / "docker-compose.gpu.yml",
    ROOT / "scripts" / "entrypoint.sh",
]

ACTIVE = re.compile(r"^([A-Z][A-Z0-9_]*)=(.*)$")
COMMENTED = re.compile(r"^# ([A-Z][A-Z0-9_]*)=")


def _template_lines() -> list[str]:
    return TEMPLATE.read_text(encoding="utf-8").splitlines()


def _template_vars() -> set[str]:
    names: set[str] = set()
    for line in _template_lines():
        match = ACTIVE.match(line) or COMMENTED.match(line)
        if match:
            names.add(match.group(1))
    return names


def _active_vars() -> dict[str, str]:
    return {m.group(1): m.group(2) for line in _template_lines() if (m := ACTIVE.match(line))}


def _compose_text() -> str:
    return "\n".join(p.read_text(encoding="utf-8") for p in TEXT_SOURCES)


def test_every_setting_is_in_the_template() -> None:
    wanted = {f"RAG_{name.upper()}" for name in Settings.model_fields} - {
        f"RAG_{n.upper()}" for n in INTERNAL_FIELDS
    }
    missing = sorted(wanted - _template_vars())
    assert not missing, f"Settings fields missing from the env template: {missing}"


def test_every_template_variable_is_real() -> None:
    settings_vars = {f"RAG_{name.upper()}" for name in Settings.model_fields}
    compose_vars = set(re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", _compose_text()))
    unknown = sorted(
        name
        for name in _template_vars()
        if name not in settings_vars and name not in compose_vars and name not in ALLOWLIST
    )
    assert not unknown, (
        f"Variables in the env template that no Settings field or compose file reads: {unknown}. "
        "Fix the name, or add it to ALLOWLIST with a reason."
    )


def test_every_compose_variable_is_in_the_template() -> None:
    used = set(re.findall(r"\$\{(RAG_[A-Z0-9_]+)", _compose_text()))
    missing = sorted(used - _template_vars())
    assert not missing, f"Compose reads these but the env template does not show them: {missing}"


def test_required_guards_are_present_and_blank() -> None:
    """A `${VAR:?}` guard needs the variable in the file, empty, for the script to fill."""
    guarded = set(re.findall(r"\$\{([A-Z0-9_]+):\?", _compose_text()))
    assert guarded, "expected the compose file to guard its secrets"
    active = _active_vars()
    for name in sorted(guarded):
        assert name in active, f"{name} is guarded in compose but missing from the template"
        assert active[name] == "", f"{name} must ship empty so the setup script generates it"


def test_generated_secrets_are_all_in_the_template() -> None:
    import importlib.util
    import sys

    spec = importlib.util.spec_from_file_location(
        "generate_secrets_for_test", ROOT / "scripts" / "generate_secrets.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    active = _active_vars()
    for key in module.GENERATORS:
        assert key in active, f"{key} is generated by scripts/generate_secrets.py but not templated"
        assert active[key] == "", f"{key} must ship empty"


def test_no_duplicate_variables() -> None:
    seen: set[str] = set()
    for line in _template_lines():
        match = ACTIVE.match(line)
        if match:
            assert match.group(1) not in seen, f"{match.group(1)} appears twice"
            seen.add(match.group(1))


def test_no_comment_after_a_value() -> None:
    """Compose and python-dotenv read `KEY=   # note` as the value '# note'."""
    for line in _template_lines():
        match = ACTIVE.match(line)
        if match:
            assert not re.match(r"^\s*#", match.group(2)), f"comment after an empty value: {line}"
            assert " #" not in match.group(2), f"inline comment, put it on its own line: {line}"


def test_sections_are_in_order() -> None:
    text = TEMPLATE.read_text(encoding="utf-8")
    titles = re.findall(r"^# (\d)\. (.+)$", text, flags=re.MULTILINE)
    assert [n for n, _ in titles] == [str(i) for i in range(1, 10)]
    assert titles[0][1].startswith("REQUIRED")
    assert titles[-1][1].startswith("Advanced")


def test_every_variable_has_a_comment_line_above_it() -> None:
    """One plain-language line per variable (secrets share the block comment above them)."""
    lines = _template_lines()
    for index, line in enumerate(lines):
        if ACTIVE.match(line) or COMMENTED.match(line):
            previous = lines[index - 1] if index else ""
            assert previous.startswith("#") or ACTIVE.match(previous), f"no comment above: {line}"


def test_template_loads_into_settings() -> None:
    settings = Settings(_env_file=TEMPLATE)  # type: ignore[call-arg]
    assert settings.llm_provider
    assert settings.cors_origins
    assert settings.session_secret.get_secret_value() == ""


@pytest.mark.parametrize("name", ["RAG_SUPERADMIN_EMAIL", "RAG_LLM_API_KEY", "RAG_ADMIN_API_KEY"])
def test_required_section_holds_the_essentials(name: str) -> None:
    text = TEMPLATE.read_text(encoding="utf-8")
    required = text.split("# 2. Email")[0]
    assert f"\n{name}=" in required


def test_default_profiles_start_the_bundled_embedder_and_no_minio() -> None:
    profiles = _active_vars()["COMPOSE_PROFILES"].split(",")
    assert "local-storage" not in profiles, "MinIO is not part of the install"
    assert _active_vars()["RAG_STORAGE_PROVIDER"] == "local"
    assert "tei" in profiles, "the default provider is tei, so its container must start"
    assert _active_vars()["RAG_EMBEDDING_PROVIDER"] == "tei"


def test_tei_is_behind_a_profile_and_the_app_does_not_hard_depend_on_it() -> None:
    """A hosted embedding API must not start (or download) the TEI container."""
    compose = (ROOT / "docker-compose.yml").read_text(encoding="utf-8")
    tei = compose.split("\n  tei:\n", 1)[1].split("\n\n", 1)[0]
    assert 'profiles: ["tei"]' in tei
    assert re.search(
        r"\n    tei:\n      condition: service_healthy\n      required: false", compose
    )


def test_host_ports_and_scraper_origins_are_configurable() -> None:
    compose = (ROOT / "docker-compose.yml").read_text(encoding="utf-8")
    active = _active_vars()
    for name, default in (
        ("RAG_APP_HOST_PORT", "8000"),
        ("RAG_SCRAPER_HOST_PORT", "8001"),
        ("RAG_DASHBOARD_HOST_PORT", "8090"),
    ):
        assert active[name] == default
        assert f"${{RAG_BIND_ADDR:-127.0.0.1}}:${{{name}:-{default}}}:" in compose
    assert "SCRAPER_CORS_ORIGINS: '${SCRAPER_CORS_ORIGINS:-" in compose
    assert "SCRAPER_CORS_ORIGINS" in active


def test_default_embedding_is_multilingual_bge_m3_everywhere() -> None:
    """The template, the compose fallback and the TEI limits agree on BGE-M3 (1024-d)."""
    active = _active_vars()
    assert active["RAG_EMBEDDING_MODEL"] == "BAAI/bge-m3"
    assert active["RAG_TEI_MODEL_ID"] == "BAAI/bge-m3"
    assert active["RAG_EMBEDDING_DIMENSIONS"] == "1024"
    compose = (ROOT / "docker-compose.yml").read_text(encoding="utf-8")
    assert "${RAG_TEI_MODEL_ID:-BAAI/bge-m3}" in compose
    assert 'MAX_CLIENT_BATCH_SIZE: "32"' in compose
    assert int(active["RAG_TEI_BATCH_SIZE"]) <= 32
