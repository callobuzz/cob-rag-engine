"""The docs claim a language as measured only when the current default fast model passed every
bar with thinking verified, and quote its row of fast-models.json exactly (conversation C9; design
section 11). The sentence is generated by benchmarks/tables.py (`language-claim` blocks)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLAIM = "English, Hindi and Hinglish, measured"
FAST = ROOT / "benchmarks/results/fast-models.json"


def _default_row() -> dict:
    doc = json.loads(FAST.read_text(encoding="utf-8"))
    key = doc["recommendations"]["default"]
    assert key, "the language claim needs a recommended fast model"
    return next(m for m in doc["models"] if m["key"] == key)


def _docs() -> dict[str, str]:
    paths = ["README.md", "docs/index.html", "CHANGELOG.md", "benchmarks/README.md"]
    return {p: (ROOT / p).read_text(encoding="utf-8") for p in paths}


def test_a_language_is_claimed_as_measured_only_when_the_default_passed() -> None:
    row = _default_row()
    if row["passes"] and row["thinking_control_verified"]:
        return
    for path, text in _docs().items():
        assert CLAIM not in text, f"{path} claims a language the default fast model did not pass"


def test_the_default_fast_model_passes_with_thinking_verified() -> None:
    row = _default_row()
    assert row["passes"], f"{row['key']} is the default but misses a bar"
    assert row["thinking_control_verified"], f"{row['key']}: thinking control not verified"


def test_the_quoted_numbers_are_the_default_rows_own() -> None:
    row = _default_row()
    pl = row["per_language"]
    quoted = [
        f"`{row['model']}`",
        f"{row['overall'] * 100:.1f}% overall",
        f"English {pl['en'] * 100:.1f}%",
        f"Hindi {pl['hi'] * 100:.1f}%",
        f"Hinglish {pl['hi-Latn'] * 100:.1f}%",
        f"{row['business_recall'] * 100:.1f}% of business questions",
        f"{row['fallback_rate'] * 100:.1f}% of its label calls",
    ]
    docs = _docs()
    for path in ("README.md", "benchmarks/README.md"):
        for value in quoted:
            assert value in docs[path], f"{path}: {value}"
    html_quoted = [v.replace("`", "") for v in quoted]
    for value in [*html_quoted[1:], row["model"]]:
        assert value in docs["docs/index.html"], f"docs/index.html: {value}"
    assert CLAIM in docs["README.md"] and CLAIM in docs["benchmarks/README.md"]
