def migrate_legacy_storage(values: dict[str, str]) -> str | None:
    """Move an earlier release's MinIO setup to local files. Returns the line to tell the
    operator, or None. Never copies anything itself."""
    if (
        not values.get("RAG_STORAGE_PROVIDER")
        and not is_legacy_minio(values)
        and (values.get("RAG_S3_ENDPOINT_CONTAINER") or values.get("RAG_S3_ACCESS_KEY"))
    ):
        # External S3 (R2, AWS, ...) from before the setting existed: keep it, never switch
        # to an empty local folder.
        values["RAG_STORAGE_PROVIDER"] = "s3"
        return None
    if not is_legacy_minio(values):
        if LEGACY_STORAGE_PROFILE in split_profiles(values.get("COMPOSE_PROFILES", "")):
            values["COMPOSE_PROFILES"] = ",".join(
                p for p in split_profiles(values["COMPOSE_PROFILES"]) if p != LEGACY_STORAGE_PROFILE
            )
        return None
    values["COMPOSE_PROFILES"] = ",".join(
        p for p in split_profiles(values.get("COMPOSE_PROFILES", "")) if p != LEGACY_STORAGE_PROFILE
    )
    apply_storage_local(values)
    return (
        "Files now live in a folder on this server instead of the bundled MinIO. While MinIO "
        f"still runs, move your existing files: {COPY_HINT}"
    )


