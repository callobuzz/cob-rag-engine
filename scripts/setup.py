@dataclass(frozen=True)
class MeasuredFast:
    """The fast-model benchmark's recommended model (an OpenRouter model id)."""

    key: str
    model: str
    provider_order: tuple[str, ...]
    p90_s: float | None
    usd_per_1000: float | None
    overall: float | None = None  # label accuracy, 0..1
    most_accurate: bool = False  # the file names it the most accurate passing model


# The file prices a label call in dollars; the wizard shows rupees, at this fixed rate (a round
# figure, not a live one: the comparison between the two models is what matters).
INR_PER_USD = 84.0


def _measured_pick(which: str, path: Path | None) -> MeasuredFast | None:
    try:
        doc = json.loads((path or FAST_MODELS_PATH).read_text("utf-8"))
        key = doc["recommendations"][which]
        row = next(m for m in doc["models"] if m["key"] == key)
        return MeasuredFast(
            key=key,
            model=str(row["model"]),
            provider_order=tuple(str(x) for x in row["provider_order"]),
            p90_s=row["latency_s"]["p90"],
            usd_per_1000=row["usd_per_1000_labels"],
            overall=row.get("overall"),
            most_accurate=doc["recommendations"].get("most_accurate") == key,
        )
    except (OSError, ValueError, KeyError, TypeError, StopIteration):
        return None


def measured_fast_model(path: Path | None = None) -> MeasuredFast | None:
    """The recommended default of benchmarks/results/fast-models.json, or None when the file
    is missing, unreadable or names no passing model (the built-in default applies)."""
    return _measured_pick("default", path)


def measured_budget_model(path: Path | None = None) -> MeasuredFast | None:
    """The file's budget option (the cheapest passing model), or None when it names none or
    names the recommended model itself."""
    budget = _measured_pick("budget", path)
    default = _measured_pick("default", path)
    if budget is None or default is None or budget.key == default.key:
        return None
    return budget


def _rupee_sign() -> str:
    """The rupee sign, or "Rs " on a console whose encoding cannot show it."""
    try:
        "₹".encode(getattr(sys.stdout, "encoding", None) or "utf-8")
    except (UnicodeEncodeError, LookupError):
        return "Rs "
    return "₹"


def _rupees(m: MeasuredFast) -> str:
    if m.usd_per_1000 is None:
        return "cost not measured"
    return f"{_rupee_sign()}{m.usd_per_1000 * INR_PER_USD:.1f}"


def fast_choice_labels(best: MeasuredFast, budget: MeasuredFast | None) -> tuple[str, str | None]:
    """The two lines of the fast-model menu, every number from fast-models.json: the
    recommended model with its accuracy and price, and the budget model with its saving."""
    accuracy = f"{best.overall:.1%}" if best.overall is not None else "accuracy not measured"
    what = "most accurate" if best.most_accurate else "best on business questions"
    recommended = (
        f"Recommended: {best.model} - {what} ({accuracy}), {_rupees(best)} per 1,000 messages"
    )
    if budget is None:
        return recommended, None
    saving = (
        f"{1 - budget.usd_per_1000 / best.usd_per_1000:.0%} cheaper "
        if budget.usd_per_1000 is not None and best.usd_per_1000
        else ""
    )
    budget_accuracy = f"{budget.overall:.1%} accurate" if budget.overall is not None else ""
    detail = ", ".join(part for part in (f"({_rupees(budget)} per 1,000)", budget_accuracy) if part)
    return recommended, f"Budget: {budget.model} - {saving}{detail}"


def fast_model_note(m: MeasuredFast) -> str:
    """One line for the fast-model question: what was measured for the suggestion."""
    via = f" (on {', '.join(m.provider_order)})" if m.provider_order else ""
    speed = f"p90 {m.p90_s:.2f} s" if m.p90_s is not None else "speed not measured"
    cost = (
        f"about ${m.usd_per_1000:.2f} per 1,000 messages it labels"
        if m.usd_per_1000 is not None
        else "cost not measured"
    )
    return (
        f"  Measured pick: {m.model}{via} passes every bar of the label benchmark, "
        f"{speed}, {cost} (benchmarks/README.md, 'Fast models')."
    )


def fast_default(provider: LLMProvider) -> str:
    """The suggested fast model: the measured recommendation for OpenRouter, whose model ids
    it uses; the built-in default for every other provider."""
    if provider.id == "openrouter":
        measured = measured_fast_model()
        if measured is not None:
            return measured.model
    return provider.fast_model


