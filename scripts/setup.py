VAR_LINE = re.compile(r"^(?P<key>[A-Z][A-Z0-9_]*)=(?P<value>.*)$")
COMMENTED_VAR_LINE = re.compile(r"^# (?P<key>[A-Z][A-Z0-9_]*)=(?P<value>.*)$")
KEY_NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")


@dataclass
class Line:
    """One line of the template: prose, `KEY=value`, or a commented-out `# KEY=value`."""

    kind: str  # "text" | "var" | "commented"
    raw: str
    key: str = ""
    value: str = ""


def parse_value(raw: str) -> str:
    """The value on the right of `=`: quotes removed, a trailing ` # comment` dropped."""
    text = raw.strip()
    if len(text) >= 2 and text[0] == "'":
        end = text.find("'", 1)
        if end != -1:
            return text[1:end]
    if len(text) >= 2 and text[0] == '"':
        match = re.match(r'^"((?:[^"\\]|\\.)*)"', text)
        if match:
            return re.sub(r"\\(.)", r"\1", match.group(1))
    return re.split(r"\s+#", text, maxsplit=1)[0].strip()


def format_value(key: str, value: str) -> str:
    """The text to write after `KEY=`: quoted only when an unquoted value would be misread."""
    if "\n" in value or "\r" in value:
        raise ValueError(f"{key}: a value cannot contain a line break")
    needs_quotes = (
        value != value.strip()
        or value[:1] in ("'", '"')
        or "$" in value
        or "`" in value
        or re.search(r"\s#", value) is not None
    )
    if not needs_quotes:
        return value
    if "'" in value:
        raise ValueError(
            f"{key}: this value cannot be stored safely (it needs quotes and contains a "
            "single quote); set it by hand in the file"
        )
    return f"'{value}'"


def parse_template(text: str) -> list[Line]:
    lines: list[Line] = []
    for raw in text.splitlines():
        active = VAR_LINE.match(raw)
        if active:
            lines.append(
                Line("var", raw, active["key"], parse_value(active["value"])),
            )
            continue
        commented = COMMENTED_VAR_LINE.match(raw)
        if commented:
            lines.append(
                Line("commented", raw, commented["key"], parse_value(commented["value"])),
            )
            continue
        lines.append(Line("text", raw))
    return lines


def parse_env_text(text: str) -> dict[str, str]:
    """Every active `KEY=value` in an env file, in file order (a later duplicate wins)."""
    values: dict[str, str] = {}
    for raw in text.splitlines():
        match = VAR_LINE.match(raw.strip())
        if match:
            values[match["key"]] = parse_value(match["value"])
    return values


RENAMED_KEYS = {"RAG_WIDGET_TRUST_PROXY_HEADERS": "RAG_TRUST_PROXY_HEADERS"}


def migrate_renamed_keys(current: dict[str, str]) -> None:
    """Carry an old variable name to its new one, in place, and drop the old one.

    Without this an old `RAG_WIDGET_TRUST_PROXY_HEADERS=true` would sit beside the
    template's new key, and the engine reads the new name first: proxy trust would turn
    off and every visitor would share the proxy's address. A new name already set wins.
    """
    for old, new in RENAMED_KEYS.items():
        if old in current:
            value = current.pop(old)
            current.setdefault(new, value)


def template_defaults(lines: Sequence[Line]) -> dict[str, str]:
    """The template's own value for each active variable."""
    return {line.key: line.value for line in lines if line.kind == "var"}


def render_env(lines: Sequence[Line], values: dict[str, str]) -> str:
    """The template filled in with `values`; keys the template lacks are appended at the end."""
    out: list[str] = []
    known: set[str] = set()
    for line in lines:
        if line.kind == "text":
            out.append(line.raw)
            continue
        known.add(line.key)
        value = values.get(line.key, line.value if line.kind == "var" else "")
        if line.kind == "var" or value:
            out.append(f"{line.key}={format_value(line.key, value)}")
        else:
            out.append(line.raw)
    extra = [(k, v) for k, v in values.items() if k not in known]
    if extra:
        out.append("")
        out.append("# --- Kept from your previous file (not part of the template) ---")
        out.extend(f"{k}={format_value(k, v)}" for k, v in extra)
    return "\n".join(out) + "\n"


SECRET_WORDS = ("KEY", "PASSWORD", "SECRET", "SALT", "TOKEN")


def is_secret_key(key: str) -> bool:
    return any(key.endswith(word) for word in SECRET_WORDS)


def mask(key: str, value: str) -> str:
    """What to show for a value: secrets become `set` / `not set`, never the value."""
    if is_secret_key(key):
        return "set" if value else "not set"
    return value if value else "(empty)"


