def finalize_values(
    values: dict[str, str],
    overrides: dict[str, str],
    previous: dict[str, str],
    *,
    current: dict[str, str] | None = None,
    defaults: dict[str, str] | None = None,
) -> None:
    """Settings that follow from others, applied in every mode (`--set` still has the last word)."""
    apply_site_domain(  # L4 install
        values, overrides, current if current is not None else {}, defaults or {}
    )
    if "COMPOSE_PROFILES" not in overrides:
        sync_tei_profile(values)
    for key, _, default, url_key in HOST_PORTS:
        # A port given with --set moves the address that points at it, unless that was set too.
        if key in overrides and url_key not in overrides and values.get(url_key):
            values[url_key] = retarget_url(values[url_key], previous.get(key, default), values[key])
    prod = values.get("RAG_ENV", "dev").strip().lower() in ("prod", "production")
    dashboard_port = values.get("RAG_DASHBOARD_HOST_PORT", "8090")
    origins = [*local_origins(dashboard_port), values.get("RAG_DASHBOARD_URL", "")]
    for key in ("RAG_CORS_ORIGINS", "SCRAPER_CORS_ORIGINS"):
        if key in overrides:
            continue
        merged = values.get(key, "")
        for origin in origins:
            if origin:
                merged = merge_cors(merged, origin, prod=prod)
        values[key] = merged


