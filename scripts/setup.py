def apply_llm(
    values: dict[str, str],
    provider: LLMProvider,
    model: str,
    api_key: str = "",
    api_base: str = "",
    fast_model: str | None = None,
) -> None:
    changed = values.get("RAG_LLM_PROVIDER") != provider.id
    old_model = values.get("RAG_LLM_MODEL", "")
    old_key = values.get("RAG_LLM_API_KEY", "")
    values["RAG_LLM_PROVIDER"] = provider.id
    values["RAG_LLM_MODEL"] = model
    # The fast helper model (question rewriting, classification) and the LLM re-ranker must
    # belong to the SAME provider, or the key would be sent to the wrong company. Both
    # default to the provider's small model; ranking is a judgement call, not reasoning.
    fast = (fast_model or fast_default(provider) or model).strip()
    values["RAG_LLM_FAST_MODEL"] = fast
    values["RAG_RERANK_LLM_MODEL"] = fast
    # The measured OpenRouter host pin goes with the measured model only: a pin belongs to it.
    measured = measured_fast_model() if provider.id == "openrouter" else None
    values["RAG_LLM_FAST_PROVIDER_ORDER"] = (
        ",".join(measured.provider_order) if measured is not None and measured.model == fast else ""
    )
    values["RAG_LLM_API_BASE"] = api_base if provider.id == "ollama" else ""
    # gpt-oss cannot switch thinking off; "low" is the level it is shipped and measured at. A "low"
    # the template wrote is dropped when the model changes to one that does not need it; a level
    # you chose yourself is kept.
    thinking = values.get("RAG_LLM_THINKING", "")
    if "gpt-oss" in model:
        values["RAG_LLM_THINKING"] = thinking or "low"
    elif thinking == "low" and (changed or old_model != model):
        values["RAG_LLM_THINKING"] = ""
    if api_key:
        values["RAG_LLM_API_KEY"] = api_key
    elif not provider.needs_key:
        # Never hand another company's key to a local server.
        if changed or not old_key:
            values["RAG_LLM_API_KEY"] = OLLAMA_PLACEHOLDER_KEY
    elif old_key == OLLAMA_PLACEHOLDER_KEY:
        values["RAG_LLM_API_KEY"] = ""


# The answer model for Hindi and Hinglish replies: the best Hindi tone and the fastest first word
# in the answer benchmark (benchmarks/README.md). Model ids are OpenRouter's.
HINDI_ANSWER_MODEL = "google/gemma-4-31b-it"


def apply_language_models(values: dict[str, str], provider: LLMProvider, enabled: bool) -> None:
    """Route Hindi and Hinglish replies to `HINDI_ANSWER_MODEL` (OpenRouter only: the model id
    is OpenRouter's, and other providers name models differently). A map already in the file
    is kept; a provider other than OpenRouter, or a no, clears it."""
