def sync_tei_profile(values: dict[str, str]) -> None:
    """`tei` is in COMPOSE_PROFILES exactly when the bundled TEI container is the embedder.

    A hosted API or in-process embeddings never call the container, so it must not start (and
    download its model). Other profiles keep their order; known ones come first.
    """
    current = split_profiles(values.get("COMPOSE_PROFILES", ""))
    wanted = {p for p in current if p != "tei"}
    if values.get("RAG_EMBEDDING_PROVIDER", "tei").strip().lower() == "tei":
        wanted.add("tei")
    ordered = [p for p in KNOWN_PROFILES if p in wanted]
    ordered += [p for p in current if p not in KNOWN_PROFILES and p in wanted]
    values["COMPOSE_PROFILES"] = ",".join(ordered)


def retarget_url(url: str, old_port: str, new_port: str) -> str:
    """`url` on a new port, only when it is this machine on the old one (a public address stays)."""
    parts = urlsplit(url)
    try:
        port = parts.port
    except ValueError:
        return url
    if parts.hostname not in ("127.0.0.1", "localhost") or port != int(old_port):
        return url
    return urlunsplit(parts._replace(netloc=f"{parts.hostname}:{new_port}")).rstrip("/")


def local_origins(port: str) -> list[str]:
    return [f"http://127.0.0.1:{port}", f"http://localhost:{port}"]


