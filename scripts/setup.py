# One public address for the whole install (deploy/install.sh asks for it; Caddy serves it).
SITE_DEV_SUFFIXES = (".localhost", ".local", ".test", ".internal", ".lan", ".home.arpa")
_LABEL = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")
SITE_DOMAIN_HINT = (
    "Use a public web address you own, like chat.sharmafurniture.in: no https://, no port, "
    "no IP address and no .local or .test name."
)


def site_domain_error(host: str) -> str | None:
    """Why `host` cannot be the install's public web address, or None when it can.

    A well-formed host name (RFC 1123 labels, at least two) that is not a development address;
    the development rule mirrors `core.install.is_dev_domain` (a test keeps them equal).
    """
    name = host.strip().lower().rstrip(".")
    bad = f"'{host}' is not a public web address. {SITE_DOMAIN_HINT}"
    if not name or len(name) > 253 or any(c in name for c in "/:@ _[]"):
        return bad
    labels = name.split(".")
    if len(labels) < 2 or not all(_LABEL.match(label) for label in labels):
        return bad
    if labels[-1].isdigit():  # an IPv4 address, not a name
        return bad
    if name == "localhost" or name.endswith(SITE_DEV_SUFFIXES):
        return bad
    return None


def drop_cors_origin(existing: str, origin: str) -> str:
    """The CORS list without one origin (a value that is not a JSON list is left alone)."""
    try:
        parsed = json.loads(existing) if existing.strip() else None
    except ValueError:
        return existing
    if not isinstance(parsed, list) or origin not in parsed:
        return existing
    return json.dumps([o for o in parsed if o != origin], separators=(",", ":"))


def apply_site_domain(
    values: dict[str, str],
    overrides: dict[str, str],
    current: dict[str, str],
    defaults: dict[str, str],
) -> None:
    """Every address, the proxy settings and production mode that follow from RAG_SITE_DOMAIN.

    A value given with --set wins; so does one the owner changed by hand in an earlier file
    (anything that is neither empty, the template's own value nor what this would write).
    """
    domain = values.get("RAG_SITE_DOMAIN", "").strip().lower().rstrip(".")
    if not domain:
        return
    values["RAG_SITE_DOMAIN"] = domain
    base = f"https://{domain}"
    derived = {
        "RAG_PUBLIC_URL": base,
        "RAG_DASHBOARD_URL": base,
        "RAG_DASHBOARD_ENGINE_URL": base,
        "RAG_DASHBOARD_SCRAPER_URL": f"{base}/scraper",
        "RAG_TRUST_PROXY_HEADERS": "true",
        "RAG_TRUSTED_PROXY_HOPS": "1",
        "RAG_ENV": "prod",
        "RAG_ACME_EMAIL": values.get("RAG_SUPERADMIN_EMAIL", "").strip(),
    }
    old = current.get("RAG_SITE_DOMAIN", "").strip().lower().rstrip(".")
    old_base = f"https://{old}" if old and old != domain else ""
    old_derived = (
        {
            "RAG_PUBLIC_URL": old_base,
            "RAG_DASHBOARD_URL": old_base,
            "RAG_DASHBOARD_ENGINE_URL": old_base,
            "RAG_DASHBOARD_SCRAPER_URL": f"{old_base}/scraper",
        }
        if old_base
        else {}
    )
    for key, wanted in derived.items():
        if key in overrides or not wanted:
            continue
        if key == "RAG_ACME_EMAIL":
            kept_by_hand = bool(current.get(key, ""))
        else:
            kept_by_hand = current.get(key, "") not in (
                "",
                defaults.get(key, ""),
                wanted,
                old_derived.get(key),
            )
        if not kept_by_hand:
            values[key] = wanted
    if old_base:
        for key in ("RAG_CORS_ORIGINS", "SCRAPER_CORS_ORIGINS"):
            if key not in overrides:
                values[key] = drop_cors_origin(values.get(key, ""), old_base)
    if "COMPOSE_PROFILES" not in overrides:
        profiles = split_profiles(values.get("COMPOSE_PROFILES", ""))
        if "proxy" not in profiles:
            profiles.append("proxy")
        values["COMPOSE_PROFILES"] = ",".join(profiles)


def production_email_error(values: dict[str, str]) -> str | None:
    """A production engine refuses a super-admin address that can never receive mail."""
    if not values.get("RAG_SITE_DOMAIN", "").strip() or not is_prod_env(values):
        return None
    address = values.get("RAG_SUPERADMIN_EMAIL", "").strip()
    if not address:
        return None
    try:
        valid_email(address, allow_special_use=False)
    except ValueError:
        return (
            f"'{address}' is not a real e-mail address, and a live server refuses it. "
            "Use one that can receive mail, like owner@sharmafurniture.in."
        )
    return None


