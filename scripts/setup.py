    kept = v.get("RAG_LLM_FAST_MODEL") if same and v.get("RAG_LLM_FAST_MODEL") else ""
    best = measured_fast_model() if pid == "openrouter" else None
    if best is None:
        return p.text("Fast model", kept or fast_default(prov), validate=valid_model)
    budget = measured_budget_model()
    recommended_line, budget_line = fast_choice_labels(best, budget)
    options = [("recommended", recommended_line)]
    if budget is not None and budget_line is not None:
        options.append(("budget", budget_line))
    options.append(("custom", "Another model (you type its id)"))
    default = "recommended"
    if kept and kept != best.model:
        default = "budget" if budget is not None and kept == budget.model else "custom"
    picked = p.choice("Which fast model?", options, default)
    if picked == "recommended":
        return best.model
    if picked == "budget" and budget is not None:
        return budget.model
    return p.text("Fast model", kept or best.model, validate=valid_model)


