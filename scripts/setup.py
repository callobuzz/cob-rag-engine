def _stdin_is_tty() -> bool:
    try:
        return sys.stdin.isatty()
    except (AttributeError, ValueError):
        return False


def _input(prompt: str) -> str:
    try:
        return input(prompt)
    except EOFError as exc:
        raise SetupAbortedError(
            "The input ended before the questions were finished. Nothing was written."
        ) from exc
    except KeyboardInterrupt as exc:
        raise SetupAbortedError("Stopped. Nothing was written.") from exc


def _secret_input(prompt: str) -> str:
    """Hidden on a real terminal; a pipe has nothing to hide from (and getpass needs a console)."""
    try:
        if _stdin_is_tty():
            return getpass.getpass(prompt)
        return input(prompt)
    except EOFError as exc:
        raise SetupAbortedError(
            "The input ended before the questions were finished. Nothing was written."
        ) from exc
    except KeyboardInterrupt as exc:
        raise SetupAbortedError("Stopped. Nothing was written.") from exc


class Prompter:
    """Asks the questions. With `yes`, every question returns its default without asking."""

    def __init__(self, *, yes: bool = False, out: Callable[[str], None] = print) -> None:
        self.yes = yes
        self.say = out

    def text(
        self,
        label: str,
        default: str = "",
        *,
        validate: Callable[[str], str] | None = None,
        example: str = "",
        allow_empty: bool = False,
    ) -> str:
        if self.yes:
            return default
        notes = [f"for example {example}"] if example else []
        if allow_empty and not default:
            notes.append("Enter to skip")
        hint = f" ({', '.join(notes)})" if notes else ""
        shown = f" [{default}]" if default else ""
        while True:
            raw = _input(f"{label}{hint}{shown}: ").strip() or default
            if not raw:
                if allow_empty:
                    return ""
                self.say("  Please enter a value.")
                continue
            if validate is None:
                return raw
            try:
                return validate(raw)
            except ValueError as exc:
                self.say(f"  {exc}")

    def secret(
        self, label: str, *, required: bool = False, validate: Callable[[str], str] = valid_secret
    ) -> str:
        """A hidden value. Enter alone returns "" (skip / keep) unless it is required."""
        if self.yes:
            return ""
        while True:
            raw = _secret_input(
                f"{label} (hidden" + ("" if required else ", Enter to skip") + "): "
            ).strip()
            if not raw:
                if not required:
                    return ""
                self.say("  This one is needed to continue.")
                continue
            try:
                return validate(raw)
            except ValueError as exc:
                self.say(f"  {exc}")

    def choice(
        self, label: str, options: Sequence[tuple[str, str]], default: str | None = None
    ) -> str:
        """Numbered menu; returns the chosen option's id. Enter takes the default."""
        ids = [option_id for option_id, _ in options]
        default_id = default if default in ids else ids[0]
        if self.yes:
            return default_id
        self.say(f"\n{label}")
        for number, (option_id, text) in enumerate(options, start=1):
            tag = "  (default)" if option_id == default_id else ""
            self.say(f"  {number}) {text}{tag}")
        default_number = ids.index(default_id) + 1
        while True:
            raw = _input(f"Choose 1-{len(options)} [{default_number}]: ").strip().lower()
            if not raw:
                return default_id
            if raw.isdigit() and 1 <= int(raw) <= len(options):
                return ids[int(raw) - 1]
            if raw in ids:
                return raw
            self.say(f"  Please type a number from 1 to {len(options)}.")

    def yes_no(self, label: str, default: bool) -> bool:
        if self.yes:
            return default
        suffix = "[Y/n]" if default else "[y/N]"
        while True:
            raw = _input(f"{label} {suffix}: ").strip().lower()
            if not raw:
                return default
            if raw in ("y", "yes"):
                return True
            if raw in ("n", "no"):
                return False
            self.say("  Please answer y or n.")

    def keep(self, what: str, shown: str) -> bool:
        """'Already set. Keep current?' Returns True to keep."""
        return self.yes_no(f"{what} is already set ({shown}). Keep current?", True)


@dataclass
class Context:
    values: dict[str, str]
    current: dict[str, str]
    existing_file: bool
    mode: str
    prompter: Prompter
    generators: dict[str, Callable[[], str]]
    gpu: bool | None = None
    rows: list[tuple[str, str]] = field(default_factory=list)

    def say(self, text: str) -> None:
        """Explanations and hints. Silent with --yes, where nothing is being asked."""
        if not self.prompter.yes:
            self.prompter.say(text)

    def row(self, label: str, detail: str) -> None:
        self.rows.append((label, detail))

    def has(self, key: str) -> bool:
        """Was this key already set in the existing file?"""
        return self.existing_file and bool(self.current.get(key))


