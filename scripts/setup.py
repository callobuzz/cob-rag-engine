def ask_fast_model(ctx: Context, prov: LLMProvider, pid: str, same: bool) -> str:
    """The fast-model question. On OpenRouter with a benchmark file: a numbered menu of the
    recommended model and the budget option, numbers read from fast-models.json, and a way to
    type another. Everywhere else: a plain text question with the provider's default."""
