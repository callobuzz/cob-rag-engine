EMAIL = re.compile(r"^[^@\s<>]+@[^@\s<>]+\.[A-Za-z]{2,}$")


# Reserved names (RFC 6761) that never receive mail. A development engine (RAG_ENV=dev)
# accepts them, a production one refuses them. The wizard is stdlib-only and cannot import
# the engine, so this mirrors SPECIAL_USE_TLDS in callobuzz_rag/accounts/email_rules.py;
# tests/unit/test_setup_wizard.py checks the two lists are equal.
SPECIAL_USE_TLDS = ("local", "test", "example", "localhost", "invalid")


def special_use_tld(address: str) -> str | None:
    domain = address.rsplit("@", 1)[-1].strip().rstrip(".").lower()
    tld = domain.rsplit(".", 1)[-1]
    return tld if tld in SPECIAL_USE_TLDS and "." in domain else None


def is_prod_env(values: dict[str, str]) -> bool:
    return values.get("RAG_ENV", "dev").strip().lower() in ("prod", "production")


def valid_email(value: str, *, allow_special_use: bool = False) -> str:
    """A well-formed address on a real domain; `.local`, `.test` and the other reserved
    names only with `allow_special_use` (a development engine)."""
    value = value.strip()
    if not EMAIL.match(value):
        raise ValueError(
            "That does not look like an e-mail address (example: admin@yourcompany.in)."
        )
    tld = special_use_tld(value)
    if tld is not None and not allow_special_use:
        raise ValueError(
            f"Addresses ending in .{tld} cannot receive e-mail, so a production engine refuses "
            "them. Use a real address (example: admin@yourcompany.in); .local, .test, "
            ".example, .localhost and .invalid only work when RAG_ENV=dev."
        )
    return value


def email_validator_for(values: dict[str, str]) -> Callable[[str], str]:
    """`valid_email` bound to the environment the file is being written for."""
    allow = not is_prod_env(values)
    return lambda value: valid_email(value, allow_special_use=allow)


def valid_url(value: str) -> str:
    value = value.strip().rstrip("/")
    parts = urlsplit(value)
    if parts.scheme not in ("http", "https") or not parts.netloc or " " in value:
        raise ValueError(
            "Enter a full address starting with http:// or https:// (example: https://rag.yourcompany.in)."
        )
    try:
        _ = parts.port
    except ValueError as exc:
        raise ValueError("The port in that address is not a number from 1 to 65535.") from exc
    return value


def valid_port(value: str) -> str:
    text = value.strip()
    if not text.isdigit() or not 1 <= int(text) <= 65535:
        raise ValueError("A port is a number from 1 to 65535 (for example 587).")
    return str(int(text))


def valid_positive_int(value: str) -> str:
    text = value.strip()
    if not text.isdigit() or not 1 <= int(text) <= 100_000:
        raise ValueError("Enter a whole number greater than zero.")
    return str(int(text))


def valid_bind_address(value: str) -> str:
    text = value.strip()
    try:
        address = ipaddress.ip_address(text)
    except ValueError as exc:
        raise ValueError("Enter an IPv4 address such as 127.0.0.1 (this machine only).") from exc
    if address.version != 4:
        raise ValueError("Enter an IPv4 address such as 127.0.0.1 (this machine only).")
    return text


def valid_host(value: str) -> str:
    text = value.strip()
    if not text or re.search(r"[\s/:@]", text):
        raise ValueError(
            "Enter just the server name, such as smtp.yourcompany.in (no http://, no port)."
        )
    return text


def valid_model(value: str) -> str:
    text = value.strip()
    if not text or re.search(r"\s", text):
        raise ValueError("A model name has no spaces (example: gpt-4o-mini).")
    return text


def valid_bucket(value: str) -> str:
    text = value.strip()
    if not re.fullmatch(r"[a-z0-9][a-z0-9.\-]{1,61}[a-z0-9]", text):
        raise ValueError(
            "A bucket name is 3 to 63 characters: lowercase letters, digits, dots, dashes."
        )
    return text


def valid_secret(value: str) -> str:
    """An API key or password: something, with nothing the file format cannot hold safely."""
    text = value.strip()
    if not text:
        raise ValueError("This cannot be empty.")
    if re.search(r"[\x00-\x1f]", text) or "'" in text or "\\" in text:
        raise ValueError(
            "Please avoid quote marks ('), backslashes and line breaks here: they cannot be stored safely."
        )
    return text


def valid_sender(value: str, *, allow_special_use: bool = True) -> str:
    text = value.strip()
    match = re.fullmatch(r"(?:[^<>\r\n]*<\s*([^<>\s]+)\s*>|([^<>\s]+))", text)
    address = (match.group(1) or match.group(2)) if match else ""
    if not address or not EMAIL.match(address):
        raise ValueError(
            'Use an address, or a name and address: "Your Product <no-reply@yourcompany.in>".'
        )
    valid_email(address, allow_special_use=allow_special_use)
    return text


def origin_of(url: str) -> str:
    parts = urlsplit(url)
    return f"{parts.scheme}://{parts.netloc}"


